import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VECTORS = ROOT / 'test-vectors' / 'legacy'
OUT = ROOT / 'legacy/src/commonTest/kotlin/io/github/flyfish233/spake2/legacy'
HEADER = '''// Original test runner: AGPL-3.0-only, Copyright (c) 2026 Flyfish233 and contributors.
// Embedded oracle data: copied from GPLv3-licensed Flyfish233/spake2-java
// commit 809ad7aa731f475c07763b1ad2c165ae192dfb5f. See third-party/spake2-java/LICENSE.
// Generated by tools/legacy_generate_tests.py; do not edit expected values.
package io.github.flyfish233.spake2.legacy

import kotlin.test.Test

'''


def flatten(v):
    return '|'.join(str(x) for x in [
        v['index'], v['passwordHex'], v['passwordHex'], v['aliceNameHex'], v['bobNameHex'],
        v['alicePrivateInput64Hex'], v['bobPrivateInput64Hex'],
        int(v['aliceDisablePasswordScalarHack']), int(v['bobDisablePasswordScalarHack']),
        v['aliceMessageHex'], v['bobMessageHex'], v['aliceKeyHex'], v['bobKeyHex']])


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    vectors = [json.loads(line) for line in (VECTORS / 'boringssl-spake2-fuzz-vectors.jsonl').read_text().splitlines()]
    assert len(vectors) == 512
    for batch in range(16):
        lines = [flatten(v) for v in vectors[batch * 32:(batch + 1) * 32]]
        name = f'LegacyOracleBatch{batch:02d}Test'
        (OUT / f'{name}.kt').write_text(HEADER + f'class {name} {{\n    @Test fun replay32IndependentOracleExchanges() {{\n        val cases = listOf(\n' + ',\n'.join('            "' + line + '"' for line in lines) + '\n        )\n        cases.forEach { replayLegacyVector(it) }\n    }\n}\n')
    deterministic = json.loads((VECTORS / 'boringssl-spake2-vectors.json').read_text())
    lines = []
    for exchange in deterministic['exchanges']:
        a, b = exchange['alice'], exchange['bob']
        ag, bg = a['generate'], b['generate']
        lines.append('|'.join(str(x) for x in [exchange['id'], a['passwordHex'], b['passwordHex'], a['myNameHex'], b['myNameHex'], ag['privateInput64Hex'], bg['privateInput64Hex'], int(a['disablePasswordScalarHack']), int(b['disablePasswordScalarHack']), ag['messageHex'], bg['messageHex'], exchange['aliceProcess']['keyHex'], exchange['bobProcess']['keyHex']]))
    process = []
    for case in deterministic['processCases']:
        p = case['process']
        process.append('|'.join([case['id'], p['theirMessageHex'], str(int(p['success'])), p['keyHex']]))
    (OUT / 'LegacyDeterministicOracleTest.kt').write_text(HEADER + 'class LegacyDeterministicOracleTest {\n    @Test fun replaySevenIndependentExchanges() {\n        listOf(\n' + ',\n'.join('            "' + line + '"' for line in lines) + '\n        ).forEach { replayLegacyVector(it) }\n    }\n    @Test fun replayHistoricalPeerInputCases() {\n        listOf(\n' + ',\n'.join('            "' + line + '"' for line in process) + '\n        ).forEach { replayLegacyProcessCase(it) }\n    }\n}\n')
    fresh_file = VECTORS / 'fresh-boringssl-oracle.json'
    if fresh_file.exists():
        fresh = json.loads(fresh_file.read_text())
        fresh_header = '''// SPDX-License-Identifier: AGPL-3.0-only
// Copyright (c) 2026 Flyfish233 and spake2 contributors
// New test expectations independently generated by tools/legacy_oracle.cc.
// BoringSSL version and complete provenance: test-vectors/legacy/fresh-boringssl-oracle.json.
package io.github.flyfish233.spake2.legacy

import kotlin.test.Test

'''
        (OUT / 'LegacyFreshOracleTest.kt').write_text(fresh_header + 'class LegacyFreshOracleTest {\n    @Test fun replayTwentyFourFreshExchanges() {\n        listOf(\n' + ',\n'.join('            "' + line + '"' for line in fresh['freshExchanges']) + '\n        ).forEach { replayLegacyVector(it) }\n    }\n    @Test fun replay108MalformedAndBoundaryPeerEncodings() {\n        listOf(\n' + ',\n'.join('            "' + line + '"' for line in fresh['freshPeerCases']) + '\n        ).forEach { replayLegacyProcessCase(it) }\n    }\n}\n')
    print(f'Generated {len(vectors)} fuzz exchanges, {len(lines)} deterministic exchanges and {len(process)} peer cases')


if __name__ == '__main__':
    main()
